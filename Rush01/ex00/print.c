#include <unistd.h>

void	print_tab(int grid[4][4])
{
	int	a;
	int	i;
	int	j;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			a = grid[i][j] + '0';
			write(1, &a, 1);
			if (j != 3)
				write(1, " ", 1);
			j++;
		}
		write(1, "\n", 1);
		i++;
	}
}
